import { createRequire } from 'node:module'
import { mkdirSync } from 'node:fs'
const require = createRequire(new URL('../../../core/http/react-ui/package.json', import.meta.url))
const { chromium, expect } = require('@playwright/test')
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
mkdirSync(new URL('./results/', import.meta.url), { recursive: true })
try {
 await page.goto(process.env.PIPELINE_TEST_URL || 'http://127.0.0.1:8097')
 const creation = page.locator('.ap-new')
 if (!await creation.evaluate(el => el.open)) await creation.locator('summary').click()
 const name = `Activity ${Date.now()}`
 await page.getByLabel('New pipeline name').fill(name)
 await page.getByRole('button', { name: 'New pipeline', exact: true }).click()
 await expect(page.getByLabel('Saved pipeline').locator('option:checked')).toHaveText(name)
 const card = page.locator('[data-node="image"]')
 await card.getByRole('combobox', { name: /^Input/ }).selectOption('direct')
 await card.getByLabel('Description', { exact: true }).fill('A blue tower')
 await card.getByRole('combobox', { name: /^Model/ }).selectOption('mock-slow')
 await card.getByLabel('Primary output').check()
 await card.getByRole('button', { name: 'Save', exact: true }).click()
 await expect(card.getByRole('button', { name: 'Save', exact: true })).toBeDisabled()
 await page.getByRole('button', { name: 'Run all', exact: true }).click()
 const activity = page.locator('.ap-running')
 const spinner = activity.locator('.ap-spinner')
 await expect(activity).toContainText('Image generation · Running')
 await expect(spinner).toBeVisible()
 expect(await spinner.evaluate(el => getComputedStyle(el).animationName)).toBe('ap-spin')
 await page.getByRole('checkbox', { name: 'Autoscroll', exact: true }).uncheck()
 const pane = page.locator('.ap-timeline')
 await pane.evaluate(el => { el.firstElementChild.style.minHeight = '2000px'; el.scrollTop = 0 })
 await expect(activity).toBeInViewport()
 const statusBox = await activity.boundingBox()
 const historyBox = await pane.boundingBox()
 const footerBox = await page.locator('.ap-timeline-footer').boundingBox()
 expect(statusBox.y).toBeGreaterThanOrEqual(historyBox.y + historyBox.height - 1)
 expect(statusBox.y + statusBox.height).toBeLessThanOrEqual(footerBox.y + 1)
 await page.screenshot({ path: new URL('./results/activity-desktop.png', import.meta.url).pathname })
 await page.emulateMedia({ reducedMotion: 'reduce' })
 expect(await spinner.evaluate(el => getComputedStyle(el).animationName)).toBe('none')
 await page.setViewportSize({ width: 390, height: 844 })
 await activity.scrollIntoViewIfNeeded()
 await expect(activity).toBeInViewport()
 expect((await activity.boundingBox()).width).toBeLessThanOrEqual(390)
 await page.getByRole('button', { name: 'Cancel', exact: true }).click()
 await expect(activity).toHaveCount(0, { timeout: 15000 })
 await card.getByRole('combobox', { name: /^Model/ }).selectOption('mock-image')
 await card.getByRole('button', { name: 'Save', exact: true }).click()
 await expect(card.getByRole('button', { name: 'Save', exact: true })).toBeDisabled()
 await page.getByRole('button', { name: 'Run all', exact: true }).click()
 await expect(activity).toBeVisible()
 await expect(activity).toHaveCount(0, { timeout: 15000 })
 expect(errors).toEqual([])
 console.log('PASS: active-task label, spinner, pinned position, manual scroll, mobile, reduced motion, cancellation and completion')
} catch (error) {
 console.error(await page.locator('body').innerText())
 throw error
} finally { await browser.close() }
