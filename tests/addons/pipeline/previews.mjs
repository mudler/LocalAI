import { createRequire } from 'node:module'
const require = createRequire(new URL('../../../core/http/react-ui/package.json', import.meta.url))
const { chromium, expect } = require('@playwright/test')
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
try {
 let failures = 0
 await page.route('**/artifact?**', async route => {
   if (failures++ < 2) await route.fulfill({ status: 503, body: 'Addon owner unavailable' })
   else await route.continue()
 })
 await page.goto(process.env.PIPELINE_TEST_URL || 'http://127.0.0.1:8097')
 const creation = page.locator('details').filter({ has: page.locator('summary', { hasText: /^Create a pipeline$/ }) })
 if (!await creation.evaluate(el => el.open)) await creation.locator('summary').click()
 const name = `Four previews ${Date.now()}`
 await page.getByLabel('New pipeline name').fill(name)
 await page.getByRole('button', { name: 'New pipeline', exact: true }).click()
 await expect(page.getByLabel('Saved pipeline').locator('option:checked')).toHaveText(name)
 const nodes = page.getByRole('button', { name: 'Nodes', exact: true })
 const executions = page.getByRole('button', { name: 'Executions', exact: true })
 await expect(nodes).toHaveAttribute('aria-pressed', 'true')
 expect(await nodes.evaluate(el => getComputedStyle(el).borderBottomWidth)).toBe('2px')
 await executions.click()
 await expect(executions).toHaveAttribute('aria-pressed', 'true')
 await nodes.click()
 const card = page.locator('[data-node="image"]')
 await card.getByRole('combobox', { name: /^Input/ }).selectOption('direct')
 await card.getByLabel('Description', { exact: true }).fill('Stone tower on black')
 await card.getByRole('combobox', { name: /^Model/ }).selectOption('mock-image')
 await card.getByLabel('Image count').selectOption('4')
 await card.getByLabel('Primary output').check()
 await card.getByRole('button', { name: 'Save', exact: true }).click()
 await expect(card.getByRole('button', { name: 'Save', exact: true })).toBeDisabled()
 await card.getByRole('button', { name: 'Run', exact: true }).click()
 await expect(card).toHaveClass(/ap-waiting/)
 await expect(card.getByText('Waiting for your selection', { exact: true })).toBeVisible()
 await expect(page.locator('.ap-planned')).toHaveCount(0)
 const outputs = page.locator('.ap-event-completed .ap-asset')
 await expect(outputs.locator('img')).toHaveCount(4, { timeout: 20000 })
 for (const img of await outputs.locator('img').all()) await expect.poll(() => img.evaluate(el => el.complete && el.naturalWidth > 0)).toBe(true)
 await expect(outputs.getByRole('alert')).toHaveCount(0)
 await expect(outputs.getByRole('button', { name: 'Load image', exact: true })).toHaveCount(0)
 await page.screenshot({ path: '/tmp/pipeline-previews-qa.png', fullPage: true })
 expect(errors).toEqual([])
 console.log('PASS: selected tabs, amber selection state, four automatic previews despite temporary failures, no misleading planning bar')
} finally { await browser.close() }
