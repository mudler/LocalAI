import { createRequire } from 'node:module'
const require = createRequire(new URL('../../../core/http/react-ui/package.json', import.meta.url))
const { chromium, expect } = require('@playwright/test')
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
try {
 await page.goto(process.env.PIPELINE_TEST_URL || 'http://127.0.0.1:8097')
 const creation = page.locator('details').filter({ has: page.locator('summary', { hasText: /^Create a pipeline$/ }) })
 if (!await creation.evaluate(el => el.open)) await creation.locator('summary').click()
 const name = `Autoscroll ${Date.now()}`
 await page.getByLabel('New pipeline name').fill(name)
 await page.getByRole('button', { name: 'New pipeline', exact: true }).click()
 await expect(page.getByLabel('Saved pipeline').locator('option:checked')).toHaveText(name)
 const source = page.locator('[data-node="source"]')
 const pane = page.locator('.ap-timeline')
 const toggle = page.getByRole('checkbox', { name: 'Autoscroll', exact: true })
 const gap = () => pane.evaluate(el => el.scrollHeight - el.clientHeight - el.scrollTop)
 async function save(i) {
   await source.getByLabel('Description', { exact: true }).fill(`Asset ${i}: ${'A stone tower with a blue roof. '.repeat(30)}`)
   await source.getByRole('button', { name: 'Save', exact: true }).click()
   await expect(source.getByRole('button', { name: 'Save', exact: true })).toBeDisabled()
   await expect(page.getByTestId('configuration-save-state')).toHaveText('All changes saved')
 }
 for (let i = 0; i < 8; i++) await save(i)
 await expect(toggle).toBeChecked()
 await expect.poll(gap).toBeLessThan(9)
 await expect.poll(() => pane.evaluate(el => el.scrollHeight > el.clientHeight + 100)).toBe(true)
 await pane.evaluate(el => { el.scrollTop -= 180 })
 await expect(toggle).not.toBeChecked()
 await pane.evaluate(el => { el.scrollTop = el.scrollHeight })
 await expect(toggle).toBeChecked()
 await toggle.uncheck()
 // Browser-delivered scroll events at the bottom must not defeat opt-out.
 await pane.evaluate(el => el.dispatchEvent(new Event('scroll')))
 await page.waitForTimeout(400)
 await expect(toggle).not.toBeChecked()
 const top = await pane.evaluate(el => el.scrollTop)
 await save(9)
 await expect(toggle).not.toBeChecked()
 await expect.poll(() => pane.evaluate(el => el.scrollTop)).toBe(top)
 await pane.evaluate(el => { el.scrollTop -= 150 })
 await page.waitForTimeout(50)
 await pane.evaluate(el => { el.scrollTop = el.scrollHeight })
 await expect(toggle).not.toBeChecked()
 await expect(toggle).toBeChecked()
 await save(10)
 await expect.poll(gap).toBeLessThan(9)
 // A late preview resize is not necessarily accompanied by a new event.
 await pane.evaluate(el => {
   const preview = document.createElement('div')
   preview.style.height = '500px'
   el.firstElementChild.append(preview)
 })
 await expect.poll(gap).toBeLessThan(9)
 await toggle.uncheck()
 await toggle.focus()
 await page.keyboard.press('Space')
 await expect(toggle).toBeChecked()
 await page.setViewportSize({ width: 390, height: 844 })
 await expect(toggle).toBeVisible()
 await expect.poll(gap).toBeLessThan(9)
 await expect(page.locator('.ap-autoscroll svg')).toBeVisible()
 expect(errors).toEqual([])
 console.log('PASS: output following, explicit opt-out, debounced up/down re-enable, late preview growth, keyboard toggle and mobile layout')
} finally { await browser.close() }
