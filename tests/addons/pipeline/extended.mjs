// Extended DAG and animation checks use real storage/runner with generated GLBs.
import { createRequire } from 'node:module'
import { mkdirSync } from 'node:fs'
import assert from 'node:assert/strict'
const require = createRequire(new URL('../../../core/http/react-ui/package.json', import.meta.url))
const { chromium, expect } = require('@playwright/test')
const base = process.env.PIPELINE_TEST_URL || 'http://127.0.0.1:8097'
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH, args: ['--no-sandbox', '--enable-unsafe-swiftshader'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
const errors = [], external = []
page.on('pageerror', e => errors.push(e.message))
page.on('request', r => { if (!r.url().startsWith(base) && !/^(blob:|data:)/.test(r.url())) external.push(r.url()) })
const card = id => page.locator(`[data-node="${id}"]`)
const completed = name => page.locator('.ap-event-completed').filter({ has: page.locator('strong', { hasText: name }) }).last()
async function rpc(data) {
 const response = await page.request.post(`${base}/rpc`, { data })
 assert.ok(response.ok(), await response.text())
 return response.json()
}
const read = async () => (await rpc({ method: 'inspect', resource: await page.getByLabel('Saved pipeline').inputValue() })).view
async function save(node) {
 await node.getByRole('button', { name: 'Save', exact: true }).click()
 await expect(page.getByTestId('configuration-save-state')).not.toHaveText('Saving changes…')
 await expect(node.getByRole('button', { name: 'Save', exact: true })).toBeDisabled()
}
async function playback(output, name) {
 await expect(output.getByLabel('Follow character')).toBeChecked()
 await output.getByRole('button', { name: 'Play animation', exact: true }).click()
 await expect.poll(async () => +(await output.getByLabel('Animation time').inputValue())).toBeGreaterThan(.1)
 await output.getByRole('button', { name: 'Pause animation', exact: true }).click()
 const canvas = output.locator('canvas')
 await output.getByLabel('Animation time').fill('0')
 await canvas.scrollIntoViewIfNeeded()
 await page.waitForTimeout(250)
 const before = await canvas.screenshot({ path: new URL(`./results/extended-${name}-pose0.png`, import.meta.url).pathname })
 await output.getByLabel('Animation time').fill('1')
 await expect(output.getByLabel('Animation time')).toHaveValue('1')
 await canvas.scrollIntoViewIfNeeded()
 await page.waitForTimeout(250)
 const after = await canvas.screenshot({ path: new URL(`./results/extended-${name}-pose1.png`, import.meta.url).pathname })
 assert.notDeepEqual(before, after, 'The visible canvas, not just the playback clock, must change when seeking')
 await output.getByLabel('Follow character').uncheck()
 await output.getByLabel('Animation time').fill('0')
 await canvas.scrollIntoViewIfNeeded()
 await page.waitForTimeout(250)
 const unfollowed = await canvas.screenshot()
 await output.getByRole('button', { name: 'Reset view', exact: true }).click()
 await canvas.scrollIntoViewIfNeeded()
 await page.waitForTimeout(250)
 assert.notDeepEqual(unfollowed, await canvas.screenshot(), 'Reset view must reframe after unfollowed locomotion')
 await output.getByLabel('Follow character').check()
 await expect(output.getByLabel('Follow character')).toBeChecked()
}
mkdirSync(new URL('./results/', import.meta.url), { recursive: true })
try {
 await page.goto(base)
 await page.getByRole('switch', { name: 'Animation (WIP)' }).check()
 await page.getByText('Create a pipeline', { exact: true }).click()
 const name = `Extended acceptance ${Date.now()}`
 await page.getByLabel('New pipeline name').fill(name)
 await page.getByRole('button', { name: 'New pipeline', exact: true }).click()
 await expect(page.getByLabel('Saved pipeline').locator('option:checked')).toHaveText(name)
 await expect(page.locator('.ap-node')).toHaveCount(12)
 assert.deepEqual(await page.locator('.ap-node:not(.ap-inactive)').evaluateAll(ns => ns.map(n => n.dataset.node)), ['source', 'review', 'image', 'extract', 'mesh'])
 await expect(card('motion-description').getByRole('radio')).toHaveCount(0)
 await card('retarget').getByRole('radio').check()
 for (const [id, model] of [['review', 'mock-review'], ['image', 'mock-image'], ['mesh', 'mock-trellis'], ['remesh', 'mock-remesh'], ['rig', 'mock-skin'], ['motion-review', 'mock-review'], ['motion', 'mock-motion'], ['retarget', 'mock-skin']]) {
   await card(id).getByRole('combobox', { name: /^Model/ }).selectOption(model)
 }
 await card('source').getByLabel('Description', { exact: true }).fill('A humanoid')
 await card('motion-description').getByLabel('Description', { exact: true }).fill('Walk forward')
 for (const id of ['review', 'image', 'extract', 'motion-review']) await card(id).getByLabel('Pause for output review').uncheck()
 await card('motion').getByLabel('Frames (30 FPS)').fill('1')
 for (const node of await page.locator('.ap-node').all()) if (await node.getByRole('button', { name: 'Save', exact: true }).isEnabled()) await save(node)
 await expect(card('motion').getByRole('button', { name: 'Run', exact: true })).toBeDisabled()
 await expect(page.getByRole('button', { name: 'Run all', exact: true })).toBeDisabled()
 await expect(card('motion').getByText(/Frames.*from 60 to 150/).first()).toBeVisible()
 await card('motion').getByLabel('Frames (30 FPS)').fill('150')
 await save(card('motion'))
 const connections = await page.locator('[data-connection]').evaluateAll(ns => ns.map(n => n.dataset.connection))
 assert.ok(connections.includes('rig:retarget') && connections.includes('motion:retarget'))
 assert.ok(!connections.some(edge => edge.includes('skin')))
 const paths = await page.locator('[data-connection$=":retarget"] path:first-child').evaluateAll(ns => ns.map(n => n.getAttribute('d')))
 assert.equal(paths.length, 2)
 assert.notEqual(paths[0].match(/H ([\d.]+)/)[1], paths[1].match(/H ([\d.]+)/)[1], 'Join branches need separate lanes')
 assert.notEqual(paths[0].match(/V ([\d.]+)/)[1], paths[1].match(/V ([\d.]+)/)[1], 'Join branches need separate endpoints')
 await expect(page.locator('.ap-run-plan')).toContainText('Motion prompt review')
 await page.getByRole('button', { name: 'Run all', exact: true }).click()
 await expect.poll(async () => (await read()).current.nodes.retarget.status, { timeout: 60000 }).toBe('succeeded')
 const states = (await read()).current.nodes
 for (const id of ['remesh', 'rig', 'motion', 'retarget']) assert.equal(states[id].status, 'succeeded')
 const retarget = completed('Apply motion')
 await expect(retarget.getByLabel('Show skeleton (through mesh)')).toBeChecked()
 const rigCanvas = retarget.locator('canvas')
 await rigCanvas.scrollIntoViewIfNeeded()
 await page.waitForTimeout(250)
 const overlay = await rigCanvas.screenshot({ path: new URL('./results/rig-overlay.png', import.meta.url).pathname })
 await retarget.getByLabel('Show skeleton (through mesh)').uncheck()
 await rigCanvas.scrollIntoViewIfNeeded()
 await page.waitForTimeout(250)
 const plain = await rigCanvas.screenshot()
 assert.notDeepEqual(overlay, plain, 'Skeleton toggle changes the visible mesh preview')
 await retarget.getByLabel('Surface view').selectOption('weights')
 await rigCanvas.scrollIntoViewIfNeeded()
 await page.waitForTimeout(250)
 const rootWeights = await rigCanvas.screenshot({ path: new URL('./results/rig-root-weights.png', import.meta.url).pathname })
 assert.notDeepEqual(rootWeights, plain, 'Weight view replaces the original surface')
 await retarget.getByLabel('Weight joint').selectOption('1')
 await rigCanvas.scrollIntoViewIfNeeded()
 await page.waitForTimeout(250)
 assert.notDeepEqual(rootWeights, await rigCanvas.screenshot({ path: new URL('./results/rig-tip-weights.png', import.meta.url).pathname }), 'Selecting a joint changes the rendered influence colors')
 await retarget.getByLabel('Surface view').selectOption('mesh')
 await expect(retarget.getByLabel('Weight joint')).toHaveCount(0)
 await rigCanvas.scrollIntoViewIfNeeded()
 await page.waitForTimeout(250)
 assert.deepEqual(await rigCanvas.screenshot(), plain, 'Original mesh view restores its materials')
 await retarget.getByLabel('Show skeleton (through mesh)').check()
 await expect(retarget.getByRole('button', { name: 'Play animation', exact: true })).toBeVisible()
 await playback(retarget, 'skinned')
 const motion = completed('Motion generation')
 await motion.getByRole('button', { name: 'Load 3D preview', exact: true }).click()
 await expect(motion.getByText('2 joints · skeleton motion')).toBeVisible()
 await playback(motion, 'skeleton')
 const downloading = page.waitForEvent('download')
 await motion.getByRole('link', { name: 'Download asset' }).click()
 const download = await downloading
 assert.equal(download.suggestedFilename(), 'asset.glb')
 assert.equal(await download.failure(), null)
 await motion.getByRole('button', { name: 'Unload preview' }).click()
 await expect(motion.locator('canvas')).toHaveCount(0)
 await motion.getByRole('button', { name: 'Load 3D preview' }).click()
 await expect(motion.getByRole('button', { name: 'Play animation' })).toBeVisible()
 await card('motion-description').getByLabel('Description', { exact: true }).fill('Run forward')
 for (const id of ['motion-review', 'motion', 'retarget']) await expect(card(id).getByText('stale', { exact: true })).toBeVisible()
 for (const id of ['mesh', 'remesh', 'rig']) await expect(card(id).getByText('succeeded', { exact: true })).toBeVisible()
 await expect(card('motion').getByRole('button', { name: 'Run', exact: true })).toBeDisabled()
 await card('motion-description').getByLabel('Description', { exact: true }).fill('Walk forward')
 await card('motion').getByRole('button', { name: 'Rerun', exact: true }).click()
 await expect(page.locator('.ap-running')).toBeVisible()
 await expect(page.locator('.ap-running')).toHaveCount(0, { timeout: 20000 })
 await expect(retarget.locator('canvas')).toHaveCount(0)
 await expect(completed('Motion generation').getByRole('button', { name: 'Play animation' })).toBeVisible()

 assert.deepEqual(errors, [])
 assert.deepEqual(external, [])
 console.log('PASS: extended DAG joins, numeric readiness, independent staleness, skeleton/skinned playback, downloads, unload/retirement')
} finally { await browser.close() }
