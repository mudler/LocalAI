"""Record the v2 acceptance fixtures and write the frozen v2 contract.

Contract v2 (multimodal-acceptance-v2-adapter) exists because contract v1 ended
as a recorded FAIL: two text-to-audio queries ranked the intended clip first
but missed the 0.01 margin by 0.0052 and 0.0063. v1 was not retuned. v2 is a new
contract with new recordings, frozen BEFORE any v2 score was computed.

What differs from v1, decided once and not iterated:

  * Scope: text, image and audio, scored through the LocalAI llama-cpp backend.
    The backend does not publish video, so there are no video queries.
  * Audio clips are 6 s, not 2 s: three independent realizations (fresh seeds)
    of the same procedural sound, one after the other. v1 gave the model about
    54 audio tokens per clip, the smallest signal of any modality.
  * Images are rendered at a different fixed instant of the same animation.
  * New seeds, derived by a fixed rule: v1 seed * 10 + segment index.
  * Audio-to-text queries are added, so audio is scored as a query as well as a
    target. Queries, distractors and thresholds are otherwise the v1 ones;
    the 0.01 margin is not loosened.

Everything is deterministic, so anyone can regenerate the committed bytes.

Usage: generate_fixtures_v2.py [--out DIR]   (needs numpy and PIL)
"""
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np

import generate_fixtures as v1

HERE = Path(__file__).resolve().parent
BASE = HERE.parent
CONTRACT_VERSION = 'multimodal-acceptance-v2-adapter'
STILL_T_V2 = 0.65
SEGMENTS = 3
CONCEPTS = ['bell', 'drum', 'water', 'typing']
LICENSE = 'MIT (owned fixture generated by test/multimodal/native_probe/generate_fixtures_v2.py; no third-party content)'


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def audio_v2(name):
    segments = [v1.SYNTH[name](np.random.default_rng(v1.SEEDS[name] * 10 + i)) for i in range(SEGMENTS)]
    # Each segment is normalized on its own so one loud realization cannot dominate.
    return np.concatenate([s / np.max(np.abs(s)) for s in segments])


def queries():
    out = []

    def others(name):
        return [c for c in CONCEPTS if c != name]

    for direction, query, target_kind in (
        ('text-to-image', 'text', 'image'),
        ('text-to-audio', 'text', 'audio'),
        ('image-to-text', 'image', 'text'),
        ('audio-to-text', 'audio', 'text'),
    ):
        for name in CONCEPTS[:3]:
            out.append({
                'id': '%s-%s' % (direction, name),
                'direction': direction,
                'query_text': v1.SEMANTIC[name] if query == 'text' else None,
                'query_fixture': None if query == 'text' else '%s-%s' % (query, name),
                'target': '%s-%s' % (target_kind, name),
                'distractors': ['%s-%s' % (target_kind, c) for c in others(name)],
            })
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--out', type=Path, default=BASE / 'fixtures-v2')
    args = parser.parse_args()
    out = args.out
    out.mkdir(parents=True, exist_ok=True)
    fixtures = []
    for name in CONCEPTS:
        (out / ('text-%s.txt' % name)).write_text(v1.SEMANTIC[name], encoding='utf-8')
        v1.DRAW[name](STILL_T_V2).save(out / ('image-%s.png' % name), optimize=False, compress_level=9)
        v1.write_wav(out / ('audio-%s.wav' % name), audio_v2(name))
        for kind, media in (('text', 'utf-8'), ('image', 'png'), ('audio', 'wav')):
            path = '%s-%s.%s' % (kind, name, {'text': 'txt', 'image': 'png', 'audio': 'wav'}[kind])
            fixtures.append({
                'id': '%s-%s' % (kind, name), 'path': path, 'sha256': sha(out / path), 'media_format': media,
                'semantic': v1.SEMANTIC[name], 'semantic_target': name, 'license': LICENSE,
            })
    (out / 'manifest.json').write_text(json.dumps({'schema_version': 1, 'contract_version': CONTRACT_VERSION, 'fixtures': fixtures}, indent=2) + '\n')

    contract = {
        'schema_version': 1,
        'contract_version': CONTRACT_VERSION,
        'supersedes': 'multimodal-acceptance-v1',
        'frozen': True,
        'freeze_policy': ('Queries, targets, distractors, thresholds and fixture hashes are frozen by the commit that adds this file, '
                          'before any v2 score exists. No tuning after inference. Any revision needs a new contract version.'),
        'scope': {
            'modalities': ['text', 'image', 'audio'],
            'excluded': 'video: the llama-cpp backend does not publish a video capability, so there are no video queries',
            'path': 'LocalAI /v1/embeddings -> llama-cpp gRPC MultimodalEmbedding, one input item per request',
        },
        'space': {
            'id': 'single-candidate-v2',
            'identity_fields': ['model_sha256', 'projector_sha256', 'pooling', 'dimensions', 'preprocessing_version'],
            'no_caption_ocr_transcription': True,
        },
        'preprocessing': {
            'version': 'adapter-v1',
            'text': 'bare UTF-8, no retrieval prefix, no template, no separator',
            'image': 'the fixture PNG bytes, unchanged; the backend decodes them',
            'audio': 'the fixture WAV bytes, unchanged; the backend resamples to the projector rate, mono float32',
        },
        'thresholds': {
            'retrieval_min_cosine_margin': 0.01,
            'media_change_min_cosine_distance': 0.001,
            'finite_nonzero_vectors': True,
            'ties_pass': False,
            'rank': 1,
            'expected_dimensions': 768,
        },
        'queries': queries(),
        'pairs': {
            'image-change': {'surrounding_text': 'Find related evidence', 'left': 'image-bell', 'right': 'image-drum'},
            'audio-change': {'surrounding_text': 'Find related evidence', 'left': 'audio-bell', 'right': 'audio-drum'},
        },
        'fixtures': {f['id']: {'path': f['path'], 'sha256': f['sha256']} for f in fixtures},
        'regeneration': 'python3 test/multimodal/native_probe/generate_fixtures_v2.py (numpy and PIL)',
    }
    (BASE / 'acceptance-contract-v2.json').write_text(json.dumps(contract, indent=2) + '\n')


if __name__ == '__main__':
    main()
