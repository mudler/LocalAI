#!/usr/bin/env node
/**
 * Writes src/icons.js from the vendored sprite (vendor/icons/sprite.svg).
 *
 * The Icon component draws each mark inline, so a page needs no sprite in its
 * document and no request: it works in a portal, a shadow root or a second
 * window the same way. The sprite stays the one source of the drawings; this
 * file is its copy as a JavaScript object, which any bundler and node can load.
 *
 * Every symbol of the kit has the same attributes (a 24 unit grid, a round
 * outline in currentColor). The script checks that, because Icon puts those
 * attributes on the group around the drawing, and a symbol with other
 * attributes would draw differently.
 *
 *   node scripts/gen-icons.mjs           # write src/icons.js
 *   node scripts/gen-icons.mjs --check   # exit 1 when src/icons.js is out of date
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SPRITE = join(ROOT, 'vendor/icons/sprite.svg')
const OUT = join(ROOT, 'src/icons.js')

// The attributes every symbol must carry, without its id.
export const SYMBOL_ATTRS = 'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"'

export function buildIcons(sprite) {
  const entries = []
  for (const m of sprite.matchAll(/<symbol id="dk-icon-([^"]+)" ([^>]*)>([\s\S]*?)<\/symbol>/g)) {
    const [, id, attrs, body] = m
    if (attrs !== SYMBOL_ATTRS) throw new Error(`icon ${id}: unexpected symbol attributes: ${attrs}`)
    entries.push(`  ${JSON.stringify(id)}: ${JSON.stringify(body.trim())},`)
  }
  if (entries.length === 0) throw new Error('no symbols in the sprite')
  return (
    '// Generated by scripts/gen-icons.mjs from vendor/icons/sprite.svg: do not edit by hand.\n' +
    '// The inner markup of each outline icon, by kit icon id.\n' +
    `export const ICONS = {\n${entries.join('\n')}\n}\n`
  )
}

export function isCurrent() {
  return existsSync(OUT) && readFileSync(OUT, 'utf8') === buildIcons(readFileSync(SPRITE, 'utf8'))
}

if (process.argv[1] && process.argv[1].endsWith('gen-icons.mjs')) {
  if (process.argv.includes('--check')) {
    if (!isCurrent()) {
      console.error('src/icons.js is out of date: run node scripts/gen-icons.mjs')
      process.exit(1)
    }
  } else {
    writeFileSync(OUT, buildIcons(readFileSync(SPRITE, 'utf8')))
    console.log('wrote src/icons.js')
  }
}
