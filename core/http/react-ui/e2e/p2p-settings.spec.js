import { test, expect } from './coverage-fixtures.js'
import { mockP2PSettings, checks, OTHER_ID, PEER_ID, RELAY_ADDR } from './p2p-settings-fixtures.js'

const PAGE = '/app/p2p/settings'
const ready = async (page) => expect(page.getByTestId('p2p-settings-page')).toBeVisible({ timeout: 15_000 })

test.describe('P2P settings: modes', () => {
  test('share mode shows the three modes, the network options and all sections', async ({ page }) => {
    await mockP2PSettings(page, { mode: 'share' })
    await page.goto(PAGE)
    await ready(page)
    await expect(page.getByTestId('p2p-mode-share').getByRole('radio')).toBeChecked()
    await expect(page.getByText('Public DHT', { exact: true })).toBeVisible()
    await expect(page.getByText('Relay for paired devices', { exact: true })).toBeVisible()
    const rail = page.getByRole('navigation', { name: 'P2P setting sections' })
    await expect(rail.getByRole('button')).toHaveText(['Network', 'Relays', 'User pairing', 'Identity'])
    await expect(page.getByTestId('p2p-share-only-note')).toHaveCount(0)
  })

  test('a mode applies at once', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'share' })
    await page.goto(PAGE)
    await ready(page)
    await page.getByTestId('p2p-mode-connect').click()
    await expect.poll(() => calls.settings).toContainEqual({ p2p_mode: 'connect' })
    await expect(page.getByTestId('p2p-share-from-here')).toBeVisible()
    await expect(page.getByRole('navigation', { name: 'P2P setting sections' }).getByRole('button')).toHaveText(['Network', 'Identity'])
  })

  test('connect only without authentication: share cannot be chosen and says why', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'connect', auth: false })
    await page.goto(PAGE)
    await ready(page)
    const share = page.getByTestId('p2p-mode-share')
    await expect(share.getByRole('radio')).toBeDisabled()
    await expect(share).toContainText('Needs authentication')
    const card = page.getByTestId('p2p-share-from-here')
    await expect(card.getByRole('link', { name: 'Turn on authentication' })).toHaveAttribute('href', /authentication/)
    await expect(card.getByRole('button', { name: 'Switch to Connect and share' })).toBeDisabled()
    await expect(page.getByText('Relay for paired devices', { exact: true })).toHaveCount(0)
    await expect(page.getByTestId('p2p-share-only-note')).toBeVisible()
    expect(calls.settings).toEqual([])
  })

  test('connect only with authentication: switch to Connect and share', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'connect' })
    await page.goto(PAGE)
    await ready(page)
    await page.getByTestId('p2p-switch-share').click()
    await expect.poll(() => calls.settings).toContainEqual({ p2p_mode: 'share' })
    await expect(page.getByTestId('p2p-mode-share').getByRole('radio')).toBeChecked()
  })

  test('off shows only the modes', async ({ page }) => {
    await mockP2PSettings(page, { mode: 'off', auth: false })
    await page.goto(PAGE)
    await ready(page)
    await expect(page.getByTestId('p2p-mode-off').getByRole('radio')).toBeChecked()
    await expect(page.getByText('Public DHT', { exact: true })).toHaveCount(0)
    await expect(page.getByRole('navigation', { name: 'P2P setting sections' }).getByRole('button')).toHaveText(['Network'])
  })

  test('a switch and the bootstrap list save their keys', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'share' })
    await page.goto(PAGE)
    await ready(page)
    await page.getByRole('switch', { name: 'Public DHT' }).click()
    await expect.poll(() => calls.settings).toContainEqual({ p2p_public_dht: false })
    await page.getByLabel('Bootstrap peers').fill(`/ip4/203.0.113.5/tcp/4001/p2p/${OTHER_ID}\n\n`)
    await page.getByTestId('p2p-bootstrap-save').click()
    await expect.poll(() => calls.settings).toContainEqual({ p2p_bootstrap_peers: [`/ip4/203.0.113.5/tcp/4001/p2p/${OTHER_ID}`] })
  })

  test('shows the tab row of Swarm, P2P with Settings as the current tab', async ({ page }) => {
    await mockP2PSettings(page, { mode: 'share' })
    await page.goto(PAGE)
    await ready(page)
    const tabs = page.getByTestId('p2p-tabs')
    await expect(tabs.getByRole('link', { name: 'Settings' })).toHaveAttribute('aria-current', 'page')
    await expect(tabs.getByRole('link', { name: 'Devices and invites' })).toHaveAttribute('href', '/app/p2p')
  })
})

test.describe('P2P settings: relays', () => {
  test.beforeEach(async ({ page }) => {
    await page.addInitScript(() => localStorage.setItem('localai-language', 'en'))
  })

  test('the table shows each relay, what invites get, and the out-of-sync warning', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'share' })
    await page.goto(`${PAGE}?section=relays`)
    await ready(page)
    await expect(page.getByTestId('relay-row-self')).toContainText('This server')
    const gated = page.locator('[data-relay="r-gated"]')
    await expect(gated).toContainText('Gated, in sync')
    await expect(gated.getByTestId('relay-pass')).toHaveText('Relay pass')
    await expect(page.locator('[data-relay="r-open"]').getByTestId('relay-pass')).toHaveText('With a warning')
    await expect(page.locator('[data-relay="r-down"]').getByTestId('relay-pass')).toHaveText('Not used')
    const warn = page.getByTestId('relay-out-of-sync')
    await expect(warn).toContainText('Office relay is out of sync.')
    await warn.getByRole('button', { name: 'Sync now' }).click()
    await expect.poll(() => calls.synced).toEqual(['r-sync'])
  })

  test('remove asks first', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'share' })
    await page.goto(`${PAGE}?section=relays`)
    await ready(page)
    await page.locator('[data-relay="r-down"]').getByTestId('relay-remove').click()
    await page.getByRole('alertdialog').getByRole('button', { name: 'Remove' }).click()
    await expect.poll(() => calls.removed).toEqual(['r-down'])
    await expect(page.locator('[data-relay="r-down"]')).toHaveCount(0)
  })

  test('run a relay: the commands name this server, a working relay can be added', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'share', check: checks.ok })
    await page.goto(`${PAGE}?section=relays`)
    await ready(page)
    await page.getByTestId('relay-run').click()
    const dialog = page.getByTestId('run-relay-dialog')
    await expect(dialog.getByTestId('command-block').first()).toContainText(`localai/relay --admin ${PEER_ID}`)
    await expect(dialog.getByTestId('command-block').nth(1)).toContainText(`local-ai p2p relay --admin ${PEER_ID}`)
    await expect(dialog.getByTestId('run-relay-add')).toBeDisabled()
    await dialog.locator('#run-relay-addr').fill(RELAY_ADDR)
    await dialog.getByTestId('run-relay-check').click()
    await expect(dialog.getByTestId('relay-check-result')).toHaveAttribute('data-kind', 'ok')
    await expect(dialog.locator('[data-step="reserve"]')).toHaveAttribute('data-state', 'ok')
    await expect(dialog.locator('[data-step="allowlist"]')).toHaveAttribute('data-state', 'ok')
    await dialog.getByTestId('run-relay-add').click()
    await expect(dialog).toHaveCount(0)
    expect(calls.added).toEqual([{ addr: RELAY_ADDR, label: '' }])
    expect(calls.removed).toEqual([])
  })

  test('run a relay: unreachable, and cancel removes what the check stored', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'share', check: checks.unreachable })
    await page.goto(`${PAGE}?section=relays`)
    await ready(page)
    await page.getByTestId('relay-run').click()
    const dialog = page.getByTestId('run-relay-dialog')
    await dialog.locator('#run-relay-addr').fill(RELAY_ADDR)
    await dialog.getByTestId('run-relay-check').click()
    await expect(dialog.getByTestId('relay-check-result')).toHaveAttribute('data-kind', 'unreachable')
    await expect(dialog.getByTestId('relay-check-result')).toContainText('Cannot reach the relay.')
    await expect(dialog.locator('[data-step="reserve"]')).toHaveAttribute('data-state', 'failed')
    await expect(dialog.getByTestId('run-relay-add')).toBeDisabled()
    await dialog.getByRole('button', { name: 'Cancel' }).click()
    await expect.poll(() => calls.removed).toEqual(['r-new'])
  })

  test('run a relay: wrong peer ID names both IDs', async ({ page }) => {
    await mockP2PSettings(page, { mode: 'share', check: checks.wrongPeer })
    await page.goto(`${PAGE}?section=relays`)
    await ready(page)
    await page.getByTestId('relay-run').click()
    const dialog = page.getByTestId('run-relay-dialog')
    await dialog.locator('#run-relay-addr').fill(RELAY_ADDR)
    await dialog.getByTestId('run-relay-check').click()
    const result = dialog.getByTestId('relay-check-result')
    await expect(result).toHaveAttribute('data-kind', 'wrong_peer')
    await expect(result).toContainText(`${OTHER_ID.slice(0, 8)}…${OTHER_ID.slice(-4)}`)
    await expect(result).toContainText('Wrong peer ID.')
  })

  test('run a relay: an unclaimed relay takes its claim code', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'share', check: checks.unclaimed })
    await page.goto(`${PAGE}?section=relays`)
    await ready(page)
    await page.getByTestId('relay-run').click()
    const dialog = page.getByTestId('run-relay-dialog')
    await dialog.locator('#run-relay-addr').fill(RELAY_ADDR)
    await dialog.getByTestId('run-relay-check').click()
    await expect(dialog.getByTestId('relay-check-result')).toHaveAttribute('data-kind', 'unclaimed')
    await dialog.getByLabel('Claim code').fill('A972-F9B0-048A')
    await dialog.getByTestId('run-relay-claim').click()
    await expect(dialog.getByTestId('relay-check-result')).toHaveAttribute('data-kind', 'ok')
    expect(calls.claimed).toEqual([{ id: 'r-new', code: 'A972-F9B0-048A' }])
  })

  test('a bad address is refused before any call', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'share' })
    await page.goto(`${PAGE}?section=relays`)
    await ready(page)
    await page.getByTestId('relay-run').click()
    const dialog = page.getByTestId('run-relay-dialog')
    await dialog.locator('#run-relay-addr').fill('relay.example.org:4001')
    await dialog.getByTestId('run-relay-check').click()
    await expect(dialog.locator('#run-relay-addr')).toHaveAttribute('aria-invalid', 'true')
    expect(calls.added).toEqual([])
  })

  test('limits of a gated relay: read from the relay, saved to it, and a restart is said', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'share' })
    await page.goto(`${PAGE}?section=relays`)
    await ready(page)
    await page.locator('[data-relay="r-sync"]').getByTestId('relay-limits').click()
    const dialog = page.getByTestId('relay-limits-dialog')
    await expect(dialog.locator('#relay-limit-dataGiB')).toHaveValue('1')
    await expect(dialog.locator('#relay-limit-minutes')).toHaveValue('60')
    await expect(dialog.locator('#relay-limit-kibps')).toHaveValue('10240')
    await expect(dialog.getByTestId('relay-limits-readonly')).toHaveCount(0)
    await expect(dialog.getByText('--rate-limit')).toHaveCount(0)

    await dialog.locator('#relay-limit-kibps').fill('64')
    await dialog.getByTestId('relay-limits-save').click()
    await expect(dialog).toHaveCount(0)
    expect(calls.limits).toEqual([{ id: 'r-sync', circuit_bytes: 1073741824, circuit_seconds: 3600, rate_bps: 65536 }])
    await expect(page.getByText('Limits saved on Office relay.')).toBeVisible()
  })

  test('limits of a gated relay without a ceiling: No limit keeps its warning and saves zeros', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'share', ceilings: {} })
    await page.goto(`${PAGE}?section=relays`)
    await ready(page)
    await page.locator('[data-relay="r-sync"]').getByTestId('relay-limits').click()
    const dialog = page.getByTestId('relay-limits-dialog')
    await dialog.getByRole('radio', { name: 'No limit' }).click()
    await expect(dialog.getByTestId('relay-no-limit-warning')).toBeVisible()
    await dialog.getByTestId('relay-limits-save').click()
    await expect(page.getByText('The relay restarted its circuit service', { exact: false })).toBeVisible()
    expect(calls.limits).toEqual([{ id: 'r-sync', circuit_bytes: 0, circuit_seconds: 0, rate_bps: 0 }])
  })

  test('limits of a relay with a ceiling: the maximum is shown, a value above it is not sent', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'share' })
    await page.goto(`${PAGE}?section=relays`)
    await ready(page)
    await page.locator('[data-relay="r-sync"]').getByTestId('relay-limits').click()
    const dialog = page.getByTestId('relay-limits-dialog')
    await expect(dialog.getByTestId('relay-limits-ceiling')).toBeVisible()
    await expect(dialog.getByTestId('relay-limit-dataGiB-max')).toHaveText('Maximum: 8 GiB')
    await expect(dialog.getByTestId('relay-limit-minutes-max')).toHaveText('Maximum: 24 h')
    await expect(dialog.getByTestId('relay-limit-kibps-max')).toHaveText('No maximum')
    // A limit with a ceiling cannot be removed, so No limit is not offered.
    await expect(dialog.getByRole('radio', { name: 'No limit' })).toHaveCount(0)
    await expect(dialog.getByText('0 means no limit')).toHaveCount(0)

    await dialog.locator('#relay-limit-dataGiB').fill('9')
    await expect(dialog.getByTestId('relay-limit-dataGiB-issue')).toContainText('Above the maximum of 8 GiB.')
    await expect(dialog.getByTestId('relay-limits-save')).toBeDisabled()
    await dialog.locator('#relay-limit-dataGiB').fill('0')
    await expect(dialog.getByTestId('relay-limit-dataGiB-issue')).toContainText('cannot be removed')
    await expect(dialog.getByTestId('relay-limits-save')).toBeDisabled()
    await dialog.locator('#relay-limit-dataGiB').fill('8')
    await expect(dialog.getByTestId('relay-limit-dataGiB-issue')).toHaveCount(0)
    await expect(dialog.getByTestId('relay-limits-save')).toBeEnabled()
    expect(calls.limits).toEqual([])
  })

  test('limits of a relay: the error of the relay stays in the dialog', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'share', refuseLimits: 'the circuit data limit of 4 GiB is above the ceiling of 2 GiB set by the relay operator' })
    await page.goto(`${PAGE}?section=relays`)
    await ready(page)
    await page.locator('[data-relay="r-sync"]').getByTestId('relay-limits').click()
    const dialog = page.getByTestId('relay-limits-dialog')
    await dialog.locator('#relay-limit-dataGiB').fill('4')
    await dialog.getByTestId('relay-limits-save').click()
    await expect(dialog.getByTestId('relay-limits-refused')).toContainText('above the ceiling of 2 GiB')
    await expect(dialog).toBeVisible()
    expect(calls.limits).toHaveLength(1)
  })

  test('limits of an open relay are shown and cannot be changed from here', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'share' })
    await page.goto(`${PAGE}?section=relays`)
    await ready(page)
    await page.locator('[data-relay="r-open"]').getByTestId('relay-limits').click()
    const dialog = page.getByTestId('relay-limits-dialog')
    await expect(dialog.getByTestId('relay-limits-readonly')).toContainText('open relay')
    await expect(dialog.locator('#relay-limit-kibps')).toHaveValue('64')
    await expect(dialog.locator('#relay-limit-kibps')).toBeDisabled()
    await expect(dialog.getByTestId('relay-limits-save')).toHaveCount(0)
    expect(calls.limits).toEqual([])
  })
})

test.describe('P2P settings: identity', () => {
  test('shows the peer ID and regenerates it only after the person ticks the box', async ({ page }) => {
    const calls = await mockP2PSettings(page, { mode: 'share' })
    await page.goto(`${PAGE}?section=identity`)
    await ready(page)
    await expect(page.getByTestId('p2p-peer-id')).toHaveText(PEER_ID)
    await page.getByTestId('regenerate-open').click()
    const dialog = page.getByTestId('regenerate-dialog')
    await expect(dialog).toContainText('12 paired devices must pair again')
    await expect(dialog.getByTestId('regenerate-confirm')).toBeDisabled()
    await dialog.getByTestId('regenerate-sure').check()
    await dialog.getByTestId('regenerate-confirm').click()
    await expect.poll(() => calls.regenerated).toBe(1)
    await expect(dialog).toHaveCount(0)
  })
})
